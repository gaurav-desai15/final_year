def make_finding(fid="f1", file="app.py", start=10, end=20, cwe="CWE-78") -> Finding:
    return Finding(
        id=fid, context_id=f"ctx-{fid}", file=file, start_line=start, end_line=end,
        function="admin_run", vulnerability_type="OS Command Injection", cwe=cwe,
        severity=Severity.HIGH, confidence=Confidence.HIGH,
        title="Command injection", description="desc",
    )


def make_report(findings, *, duration=12.5, stages=None) -> AnalysisReport:
    return AnalysisReport(
        repo="examples/app", languages=["python"], model="test-model",
        findings=findings,
        stats=RunStats(
            candidate_contexts_analyzed=4, llm_calls=4, duration_seconds=duration,
            stage_timings=stages or {"joern_parse": 8.0, "llm_analysis": 4.0},
            peak_memory_mb=256.0,
        ),
    )


def make_case(**kwargs) -> BenchmarkCase:
    defaults = dict(
        id="case1", repo="examples/app", language="python", label=CaseLabel.VULNERABLE,
        expected=[GroundTruth(id="gt1", cwe="CWE-78", file="app.py",
                              start_line=10, end_line=20)],
    )
    defaults.update(kwargs)
    return BenchmarkCase(**defaults)


def make_run(cases: list[CaseResult], *, label="test", synthetic=False) -> RunResult:
    return RunResult(
        metadata=RunMetadata(
            run_id=f"2026-01-01T00-00-00Z__{label}", label=label,
            datasets=["test"], synthetic=synthetic,
            created_at=_dt.datetime(2026, 1, 1, tzinfo=_dt.timezone.utc),
        ),
        cases=cases,
    )


