class TestStorage:
    def test_save_and_load_roundtrip(self, tmp_path):
        case = evaluate_case(make_case(), make_report([make_finding()]),
                             MatchPolicy(), dataset_name="d")
        run = make_run([case], label="baseline")
        directory = save_run(run, results_dir=tmp_path, report_markdown="# hi")

        assert (directory / "manifest.json").exists()
        assert (directory / "metrics.json").exists()
        assert (directory / "report.md").read_text() == "# hi"

        loaded = load_run(run.metadata.run_id, tmp_path)
        assert loaded.metadata.run_id == run.metadata.run_id
        assert loaded.cases[0].metrics.true_positives == 1

    def test_run_ids_are_unique_and_sortable(self):
        early = new_run_id("x", _dt.datetime(2026, 1, 1, tzinfo=_dt.timezone.utc))
        late = new_run_id("x", _dt.datetime(2026, 6, 1, tzinfo=_dt.timezone.utc))
        assert early < late
        assert early.endswith("__x")

    def test_run_id_sanitizes_label(self):
        run_id = new_run_id("prompt v2/experimental!",
                            _dt.datetime(2026, 1, 1, tzinfo=_dt.timezone.utc))
        assert "/" not in run_id and " " not in run_id

    def test_resolve_by_label_and_latest(self, tmp_path):
        first = make_run([], label="baseline")
        first.metadata.run_id = "2026-01-01T00-00-00Z__baseline"
        save_run(first, results_dir=tmp_path)
        second = make_run([], label="prompt-v2")
        second.metadata.run_id = "2026-02-01T00-00-00Z__prompt-v2"
        save_run(second, results_dir=tmp_path)

        assert resolve_run("latest", tmp_path).name == second.metadata.run_id
        assert resolve_run("baseline", tmp_path).name == first.metadata.run_id
        assert resolve_run(first.metadata.run_id, tmp_path).name == first.metadata.run_id
        assert len(list_runs(tmp_path)) == 2

    def test_label_resolves_to_most_recent_carrying_it(self, tmp_path):
        # Re-measuring a baseline must not break `compare baseline latest`.
        for stamp in ("2026-01-01T00-00-00Z", "2026-03-01T00-00-00Z"):
            run = make_run([], label="baseline")
            run.metadata.run_id = f"{stamp}__baseline"
            save_run(run, results_dir=tmp_path)
        assert resolve_run("baseline", tmp_path).name.startswith("2026-03-01")

    def test_unknown_run_raises(self, tmp_path):
        save_run(make_run([], label="x"), results_dir=tmp_path)
        with pytest.raises(FileNotFoundError, match="No run matching"):
            resolve_run("nope", tmp_path)

    def test_no_runs_raises(self, tmp_path):
        with pytest.raises(FileNotFoundError, match="No archived benchmark runs"):
            resolve_run("latest", tmp_path)


