class TestMetrics:
    def test_precision_recall_f1(self):
        m = Metrics(true_positives=3, false_positives=1, false_negatives=1)
        assert m.precision == 0.75
        assert m.recall == 0.75
        assert m.f1 == pytest.approx(0.75)

    def test_zero_division_is_safe(self):
        m = Metrics()
        assert (m.precision, m.recall, m.f1) == (0.0, 0.0, 0.0)

    def test_addition(self):
        total = Metrics(true_positives=1, false_positives=2) + Metrics(
            true_positives=3, false_negatives=4
        )
        assert total.true_positives == 4
        assert total.false_positives == 2
        assert total.false_negatives == 4

    def test_aggregation_excludes_failed_cases(self):
        ok = evaluate_case(make_case(), make_report([make_finding()]),
                           MatchPolicy(), dataset_name="d")
        failed = CaseResult(case_id="bad", dataset="d", repo="x", status="error",
                            error="boom", ground_truth_total=5)
        run = make_run([ok, failed])
        assert M.overall(run).true_positives == 1
        assert M.overall(run).false_negatives == 0  # the failed case contributes nothing
        assert len(run.ok_cases()) == 1

    def test_runtime_stats(self):
        a = evaluate_case(make_case(), make_report([make_finding()], duration=10.0),
                          MatchPolicy(), dataset_name="d", duration_seconds=10.0)
        b = evaluate_case(make_case(id="c2"), make_report([make_finding()], duration=30.0),
                          MatchPolicy(), dataset_name="d", duration_seconds=30.0)
        stats = M.runtime_stats(make_run([a, b]))
        assert stats["total_seconds"] == 40.0
        assert stats["mean_seconds"] == 20.0
        assert stats["median_seconds"] == 20.0
        assert stats["max_seconds"] == 30.0

    def test_stage_breakdown_shares_sum_to_100(self):
        case = evaluate_case(make_case(), make_report([make_finding()]),
                             MatchPolicy(), dataset_name="d")
        breakdown = M.stage_breakdown(make_run([case]))
        assert sum(v["share_pct"] for v in breakdown.values()) == pytest.approx(100.0, abs=0.2)
        # Sorted slowest-first so the dominant stage is the first row.
        assert list(breakdown) == ["joern_parse", "llm_analysis"]

    def test_by_cwe_attribution(self):
        case = evaluate_case(
            make_case(), make_report([make_finding(), make_finding(fid="f2", file="z.py",
                                                                   cwe="CWE-22")]),
            MatchPolicy(), dataset_name="d",
        )
        by_cwe = M.by_cwe(make_run([case]))
        assert by_cwe["CWE-78"].true_positives == 1
        assert by_cwe["CWE-22"].false_positives == 1

    def test_common_false_positives_groups_by_class(self):
        report = make_report([
            make_finding(fid="a", file="x.py"), make_finding(fid="b", file="y.py"),
        ])
        case = evaluate_case(make_case(), report, MatchPolicy(), dataset_name="d")
        top = M.common_false_positives(make_run([case]))
        assert top[0] == ("CWE-78 / OS Command Injection", 2)

    def test_summarize_is_json_serializable(self):
        case = evaluate_case(make_case(), make_report([make_finding()]),
                             MatchPolicy(), dataset_name="d")
        json.dumps(M.summarize(make_run([case])), default=str)

    @pytest.mark.parametrize("raw,expected", [
        ("CWE-78", "CWE-78"), ("cwe 78", "CWE-78"),
        ("CWE-78: Improper Neutralization", "CWE-78"),
        ("cwe_79", "CWE-79"), ("", ""), ("not a cwe", ""),
    ])
    def test_normalize_cwe(self, raw, expected):
        assert normalize_cwe(raw) == expected


