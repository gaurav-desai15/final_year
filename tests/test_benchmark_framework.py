class TestEvaluator:
    def test_true_positive(self):
        result = evaluate_case(
            make_case(), make_report([make_finding()]), MatchPolicy(), dataset_name="d"
        )
        assert result.metrics.true_positives == 1
        assert result.metrics.false_positives == 0
        assert result.metrics.recall == 1.0

    def test_false_positive_and_negative(self):
        result = evaluate_case(
            make_case(), make_report([make_finding(file="other.py")]),
            MatchPolicy(), dataset_name="d",
        )
        assert result.metrics.false_positives == 1
        assert result.metrics.false_negatives == 1
        assert result.metrics.precision == 0.0

    def test_safe_case_with_no_findings_is_a_true_negative(self):
        case = make_case(label=CaseLabel.SAFE, expected=[])
        result = evaluate_case(case, make_report([]), MatchPolicy(), dataset_name="d")
        assert result.metrics.true_negatives == 1
        assert result.metrics.false_positives == 0

    def test_safe_case_with_findings_yields_no_true_negative(self):
        case = make_case(label=CaseLabel.SAFE, expected=[])
        result = evaluate_case(case, make_report([make_finding()]), MatchPolicy(),
                               dataset_name="d")
        assert result.metrics.true_negatives == 0
        assert result.metrics.false_positives == 1

    def test_vulnerable_case_never_yields_true_negatives(self):
        # "Not vulnerable" isn't enumerable for a vulnerable case, so TN stays 0.
        result = evaluate_case(make_case(), make_report([make_finding()]),
                               MatchPolicy(), dataset_name="d")
        assert result.metrics.true_negatives == 0

    def test_scope_paths_exclude_out_of_scope_findings(self):
        case = make_case(scope_paths=["src/"])
        report = make_report([make_finding(file="vendor/lib.py"),
                              make_finding(fid="f2", file="src/app.py")])
        result = evaluate_case(case, report, MatchPolicy(), dataset_name="d")
        # The vendor finding is ignored entirely -- not counted as an FP.
        assert result.findings_reported == 1
        assert result.metrics.false_positives == 0

    def test_case_policy_overrides_dataset_policy(self):
        case = make_case(match_policy={"require_cwe": True})
        report = make_report([make_finding(cwe="CWE-89")])
        result = evaluate_case(case, report, MatchPolicy(), dataset_name="d")
        assert result.metrics.true_positives == 0

    def test_timings_are_carried_through(self):
        result = evaluate_case(make_case(), make_report([make_finding()]),
                               MatchPolicy(), dataset_name="d", duration_seconds=30.0)
        assert result.duration_seconds == 30.0
        assert result.stage_timings["joern_parse"] == 8.0
        assert result.peak_memory_mb == 256.0


