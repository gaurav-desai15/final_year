class TestReports:
    def _run(self, **kwargs) -> RunResult:
        case = evaluate_case(
            make_case(),
            make_report([make_finding(), make_finding(fid="f2", file="z.py", cwe="CWE-22")]),
            MatchPolicy(), dataset_name="d",
        )
        return make_run([case], **kwargs)

    def test_run_report_contains_headline_metrics(self):
        md = render_run_report(self._run())
        assert "# Benchmark run" in md
        assert "Precision" in md and "Recall" in md and "F1" in md
        assert "Stage breakdown" in md

    def test_synthetic_runs_are_banner_flagged(self):
        assert "Synthetic run" in render_run_report(self._run(synthetic=True))
        assert "Synthetic run" not in render_run_report(self._run(synthetic=False))

    def test_small_sample_warning_shown(self):
        assert "Small sample" in render_run_report(self._run())

    def test_comparison_reports_deltas_and_verdict(self):
        baseline = self._run(label="baseline")
        candidate = self._run(label="v2")
        candidate.cases[0].metrics = Metrics(true_positives=2, false_positives=0)
        md = render_comparison(baseline, candidate)
        assert "Metric deltas" in md
        assert "Verdict" in md
        assert "Improvement" in md

    def test_comparison_flags_regressions(self):
        baseline = self._run(label="baseline")
        baseline.cases[0].metrics = Metrics(true_positives=5, false_positives=0)
        candidate = self._run(label="v2")
        candidate.cases[0].metrics = Metrics(true_positives=1, false_positives=4)
        assert "Regression" in render_comparison(baseline, candidate)

    def test_multi_version_table_uses_labels_not_hardcoded_names(self):
        runs = [self._run(label="anything-goes"), self._run(label="another")]
        md = render_multi_version_table(runs)
        assert "anything-goes" in md and "another" in md

    def test_multi_version_table_handles_empty(self):
        assert "No runs to compare" in render_multi_version_table([])

    def test_analysis_document_has_all_sections(self):
        md = render_analysis_document(self._run())
        for heading in [
            "## 1. Overall statistics",
            "## 2. Per-project statistics",
            "## 3. Per-CWE statistics",
            "## 4. Most common false positives",
            "## 5. Most common false negatives",
            "## 6. Top missed vulnerability classes",
            "## 7. Runtime and performance",
            "## 8. Detection distribution",
            "## 10. Recommendations",
        ]:
            assert heading in md, f"missing {heading}"

    def test_analysis_document_includes_history_when_given(self):
        md = render_analysis_document(self._run(), history=[self._run(label="old")])
        assert "## 9. History" in md

    def test_recommendations_flag_synthetic_runs(self):
        md = render_analysis_document(self._run(synthetic=True))
        assert "Produce a real baseline first" in md


