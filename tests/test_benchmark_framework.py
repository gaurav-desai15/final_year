class TestLoader:
    def test_shipped_datasets_all_parse(self):
        """Every dataset in the repo must load; a broken one fails CI here."""
        paths = discover_datasets()
        assert paths, "no datasets found"
        for path in paths:
            dataset = load_dataset(path)
            assert dataset.name

    def test_bundled_examples_ground_truth(self):
        dataset = load_datasets(["bundled-examples"])[0]
        assert dataset.verified is True
        assert len(dataset.active_cases()) == 2
        assert dataset.ground_truth_count() == 5
        # The tight line policy is what keeps safe siblings out of the TPs.
        assert dataset.match_policy["require_line"] is True

    def test_cve_template_is_skipped_by_default(self):
        # The template must never contribute placeholder ground truth to a run.
        dataset = load_datasets(["cve-repos"])[0]
        assert dataset.active_cases() == []
        assert dataset.verified is False

    def test_ground_truth_ids_autogenerated(self, tmp_path):
        path = tmp_path / "d.yaml"
        path.write_text(
            "name: d\ncases:\n  - id: c1\n    repo: ./x\n    expected:\n"
            "      - cwe: CWE-78\n        file: a.py\n",
            encoding="utf-8",
        )
        dataset = load_dataset(path)
        assert dataset.cases[0].expected[0].id == "c1-gt1"

    def test_defaults_propagate_to_cases(self, tmp_path):
        path = tmp_path / "d.yaml"
        path.write_text(
            "name: d\ndefault_language: python\ndefault_analyze_args: ['--no-dataflow']\n"
            "cases:\n  - id: c1\n    repo: ./x\n",
            encoding="utf-8",
        )
        case = load_dataset(path).cases[0]
        assert case.language == "python"
        assert case.analyze_args == ["--no-dataflow"]

    def test_duplicate_case_ids_rejected(self, tmp_path):
        path = tmp_path / "d.yaml"
        path.write_text(
            "name: d\ncases:\n  - id: c1\n    repo: ./x\n  - id: c1\n    repo: ./y\n",
            encoding="utf-8",
        )
        with pytest.raises(DatasetError, match="duplicate case id"):
            load_dataset(path)

    def test_duplicate_ground_truth_ids_rejected(self, tmp_path):
        path = tmp_path / "d.yaml"
        path.write_text(
            "name: d\ncases:\n  - id: c1\n    repo: ./x\n    expected:\n"
            "      - id: g\n        file: a.py\n      - id: g\n        file: b.py\n",
            encoding="utf-8",
        )
        with pytest.raises(DatasetError, match="duplicate ground-truth id"):
            load_dataset(path)

    def test_missing_file_raises(self, tmp_path):
        with pytest.raises(DatasetError, match="not found"):
            load_dataset(tmp_path / "nope.yaml")

    def test_invalid_yaml_raises(self, tmp_path):
        path = tmp_path / "d.yaml"
        path.write_text("name: [unclosed\n", encoding="utf-8")
        with pytest.raises(DatasetError, match="invalid YAML"):
            load_dataset(path)

    def test_unknown_dataset_name_lists_available(self):
        with pytest.raises(DatasetError, match="Available:"):
            load_datasets(["does-not-exist"])

    def test_resolve_repo_keeps_urls_and_absolutizes_paths(self):
        assert resolve_repo("https://github.com/a/b") == "https://github.com/a/b"
        assert resolve_repo("examples/x").startswith("/")


